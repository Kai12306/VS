#include <stdio.h>

int main()
{
	int a, b;
	scanf("%d", &a);
	if (a <= 100000)
	{
		b = 0.1*a;
	}
	else if (a > 100000 && a <= 200000)
	{
		b = 100000 * 0.1 + (a - 100000) * 0.075;
	}
	else if (a > 200000 && a <= 400000)
	{
		b = 200000 * 0.075 + (a - 200000) * 0.015;
	}
	else if (a > 400000 && a <= 600000)
	{
		b = 400000 * 0.1 + (a - 400000) * 0.03;
	}
	else if (a > 600000 && a <= 1000000)
	{
		b = 600000 * 0.1 + (a - 600000) * 0.015;
	}
	else if (a > 1000000)
	{
		b = 1000000 * 0.1 + (a - 1000000) * 0.001;
	}
	printf("%d\n", b);
	return 0;
}
