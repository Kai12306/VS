#include<stdio.h>
int main()
{

	//数组的算法题
	 
	//需求:
	// 已知数组元素为33,5,22、44、55
	// 请找出数组中最大值，并打印在控制台
	 
	//1.定义数组
	int arr[5] = { 33,5,22,44,55 };
	 
	 //2.定义变量,记录最大值
	// [核心] 打擂台法: 先让第一个元素当擂主, 后面逐个上去比
	// [易错] 不能写 max = 0 —— 如果数组全是负数, 最大值会被错误地算成 0
	int max = arr[0];

//3.
//遍历数组，得到每一个元素，拿着遍历到的元素 max 进行比较。

//遍历到的元素小于等于  max 里面记录的数据   不做任何处理
//遍历到的元素大于      max 里面记录的数据   max 就要修改成新的数值。


	//思考一，循环是不是一定要从零索引开始？
	// 不是的。如果 Max 的默认值记录的是零索引的，循环就可以从一开始提高效率。

	/*
	    思考二，max 的默认值可以写为0吗？

		不可以的。如果数组里所有的数据都是负数，循环结束之后得到的最大值是0，此时会给别人产生误解。
		max的默认值一定要是数组中已经存在的数据，一般都是把零索引当成默认值。
	*/


	int len = sizeof(arr) / sizeof(arr[0]);

	// [优化] 因为 arr[0] 已经在擂台上, 可以从 i=1 开始, 少比一次
	for (int i = 0;i < len;i++)
	{
		if (arr[i]>max)
		{
			max = arr[i];
		}
	}

	//4.输出并打印max
	printf("%d\n",max);


	int min = arr[0];

	for (int i = 0;i < len;i++)
	{
		if (arr[i] < min)
		{
			min = arr[i];
		}
	}

	printf("%d\n", min);

	 
	//求最值
	//求和
	//求反转数组
	//打乱数据
	//查找与排序




	return 0;
}




