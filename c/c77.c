#include<stdio.h>
int main()
{
	//字符串:会有一个隐含的结束标记:\0
	//\0:是一个整体

	
	//两种定义字符串的方式
	//利用字符数字+双引号的方式定义
	char str1[4] = "abc";
	printf("%s\n",str1);

	//细节一:
	// 在底层实际存储的时候，C 语言还是会把字符串 abc 转化成字符数组进行保存，并在末尾还要加上杠零。
	//例如:{'a','b','c','\0'}

	//细节二:
	//数组的长度,要么不写,要么提前预留出来结束标记的空间

	//细节三:
	//利用字符数字+双引号的方式定义:字符串内容可以发生改变
	str1[0] = 'h';
	printf("%s\n", str1);

	return 0;
}







