#include<stdio.h>
int main()
{
	//一,

	//算术运算符


	// [核心] 字符参与运算时自动用它的 ASCII 码值; 'a'=97, 所以 97+1=98
	char c = 'a';
	int i = c + 1;
	printf("%d\n", i);  //98
	printf("%c\n", c);  //'a'

	//字符转数字
	// 'a'  'A'  '0'
	printf("%d\n",'a');
	// [记忆] 常用 ASCII: 'a'=97  'A'=65  '0'=48  \0=0  \n=10
	//        大小写相差 32, 数字字符和本身数值相差 48
	printf("%d\n", 'A');
	printf("%d\n", '0');


	//自增自减运算符
	// ++和--,可以写在变量之前或者之后
	//1.需要单独一行使用
	
	//二.


	
	int a = 10;
	a++;              //也可以打成++a
	printf("%d\n",a);

	int b = 10;
	--b;
	printf("%d\n", b);

	//2.参与计算
	//实际开发中基本无人使用,单考试会有一到两个选择题.四分左右
	//不单独成行时,先++ 后++,会存在不同

	int s = 10;    //先用后加
	// [核心] s++ 是"先用后加": 先把 10 给 d, s 再加成 11
	int d = s++;

	printf("%d\n", s);  //11
	printf("%d\n", d);  //10



	int e = 10;    //先加后用
	// [核心] ++e 是"先加后用": e 先变成 11, 再把 11 给 f
	int f = ++e;

	printf("%d\n", e);  //11
	printf("%d\n", f);  //11


	int g = 10;
	int h = g++;    //先用后加,使用原来的值
	                //printf("%d\n", h);执行完毕之后,值变成11.即 g=11
	int j = ++g;
	                //以11为基数进行自增
	                //先加后用,使用自增之后的值




	printf("%d\n", g);  //12
	printf("%d\n", h);  //10
	printf("%d\n", j);  //12


	//三,



	int a1 = 10;
	int a2 = 5;
	// [警告] 这种同一表达式里对同一变量多次自增/自减, 属于"未定义行为"(UB)!
	//        Windows 和 Linux 结果不同(7 vs 6), 就是因为标准没规定求值顺序
	//        考试会考, 但真实开发绝对不要这么写
	int a3 = a1++ + ++a1 - --a2 - a1--;
	//  windows:  11+11-4-11 = 7
	

	printf("%d\n",a3);

	//windows:7
	//前缀优先于后缀,即先加加优先于后加加
	//前缀先统一自增或者自减,再把结果拿出来用
	//int a1 = 10;
	//++a1 + ++a1;
	//  12 +  12  = 24
	//后缀先统一进行使用,等整个表达式都用完了,再进行自增
	//a1++   +a1++;
	// 10  +  10 = 20
	// a1++ + ++a1 - --a2 - a1--
	// 10  +  12  -4  -12  =6
	// a1++已经加过一次,所以第二个是12,--a2也是同理
	
	
	
	
	//Linux,Mac:6
	//前缀与后缀的优先级相同
	//从左都有依次进行计算
	//每一个前缀与后缀都是一个独立的个体
	//int a1 = 10;
	//++a1 + ++a1;
	// 11  +  12  =23


	//四,

	//(均默认为windows系统)

	int k = 10;
	// [警告] 同上, 一行里多次改同一个变量 = UB, 换个编译器结果就变
	//        你自己的注释里推的是 Windows 的答案, 记住"这是实现定义的"就行
	int k1 = k++ + k++;
	int k2 = ++k+ ++k;
	int k3 = ++k + k++;
	int k4 = k++ + ++k;
	printf("%d\n", k1);
	printf("%d\n", k2);
	printf("%d\n", k3);
	printf("%d\n", k4);

	//k1 10+10   k=12
	//k2 14+14   k=14
	//k3 15+15   k=16
	//k4 17+17   k=18
	//前缀优先于后缀,故先计算++k,再算k++


	int l= 10;
	int l1 = l++ + l++ +l ;
	int l2 = ++l + ++l +l ;
	int l3 = ++l + l++ +l ;
	int l4 = l++ + ++l +l ;
	printf("%d\n", l1);
	printf("%d\n", l2);
	printf("%d\n", l3);
	printf("%d\n", l4);
	//l1:10,10,10  l=12
	//l2:14,14,14  l=14
	//13:15,15,15  l=16
	//l4:17,17,17  l=18














	return 0;
}






