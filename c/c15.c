#include<stdio.h>

int main()
{
	// +  -  *
	//可使用数字直接进行计算

	printf("%d\n", 3 + 2);
	printf("%d\n", 3 - 2);
	printf("%d\n", 3 * 2);

	//或者使用变量进行计算
	printf("%.2lf\n", 1.1 + 1.01);
	printf("%.2lf\n", 1.1 - 1.01);
	printf("%.2lf\n", 1.1 * 1.01);


	int a = 10;
	int b = 20;
	printf("%d\n", a + b);
	printf("%d\n", a - b);
	printf("%d\n", a * b);

	//除法(/)
	printf("%d\n", 10 / 2);  //5
	// [核心] 整数除法: 结果还是整数, 小数部分直接丢弃(不是四舍五入!)

	//取余(%)
	printf("%d\n", 10 % 2);
	printf("%d\n", 10 % 3);

	//通用细节
	//1.整数计算,结果一定是一个整数
	printf("%d\n", 10 / 2);  //5
	printf("%d\n", 10 / 3);  //3  抛弃小数点后的数字,无论加减乘除
	// [易错] 只对除法/取余"丢小数"; 加 减 乘 的结果本来就是整数, 不存在丢弃

	//2.小数计算,结果一定是一个小数


	//3.整数与小数运算,结果一定是小数
	printf("%lf\n",10.0+3);

	//4.小数直接参与计算,结果可能精确
	printf("%lf\n", 6.6666666666666666 + 3.3333333333333333);
	// [补充] 小数在内存里是近似存储, 不一定精确相加; 这里刚好是 10
	printf("%.20lf\n", 10.0 / 3.0);


	//除法的细节   不能除以零
	//printf("%d\n",10 /0);

	//取余的细节
	//1.运算的数据全都是整数
	printf("%d\n", 10 / 3);

	//2.获取余数的正负,是与第一个数字保持一致的
	printf("%d\n", 10 / 3);   //3
	printf("%d\n", -10 / 3);  //-3
	// [重要] 整数除法是"向零截断": -10/3 = -3.333 -> -3 (不是向下取整的 -4)
	printf("%d\n", 10 / -3);  //-3
	// [补充] 余数的符号跟着"第一个操作数"走: -10%3 = -1, 10%-3 = 1

	//3.不能除以0






	return 0;
}