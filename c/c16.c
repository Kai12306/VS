#define _CRT_SECURE_NO_WARNINGS
#include<stdio.h>
int main()
{
	//需求:键盘上输入一个三位数,将其拆分为个位,十位,百位.打印在控制台
	//输出结果
	 /* 个位 : 3  
      十位 : 2
      百位 : 1*/

	//1.键盘录入一个三位数
	printf("请输入一个三位数:\n");
	int num;
	scanf("%d", &num);
	
	//2.拆分
	// [核心] 取个位: 对 10 取余, 余数就是个位
	int ge = num % 10;
	// [核心] 取十位: 先 /10 把个位挤掉, 再 %10 取新末位
	int shi = num / 10 % 10;
	// [核心] 取百位: 三位数 /100 剩下的就是百位
	int bai = num / 100;
	int qian = num / 1000;
	// [注意] 输入是三位数, 千位恒为 0; 这行留着能验证"位数不够就是0"

	printf("个位是:%d\n",ge);
	printf("十位是:%d\n",shi);
	printf("百位是:%d\n",bai);
	printf("千位是:%d\n", qian);
	// [优化] 若要支持任意位数, 应换成 while 循环反复 %10 取末位 / /10 去掉末位, 而不是写死几个变量


	// [补充] 口诀: / 往回缩(丢掉末位), % 留尾巴(留下末位) —— 两者别再搞反
	return 0;
}








