#include<stdio.h>
int main()

{
	//内存地址也被称为指针

	//一般指针变量也会被叫做指针
	//注意:需要分清

	//指针变量:存储内存地址的变量


	// 指针变量定义格式
//
//   数据类型   *   变量名
//      |        |     |
//      |        |     +-- 自己起的名字
//      |        +-------- 标记
//      +----------------- 要跟指向变量的类型保持一致
//
//
//   int a = 10;
//   int* p1 = &a;
//
//   double b = 10;
//   double* p2 = &b;

	//指针的作用:
//查询数据，存储数据，参数传递，内存管理。

	//利用指针去获取变量中的数据或存储数据

	int a = 10;

	//1.定义一个指针去指向变量a
	int* p1 = &a;
	//赋值已经分配空间的内存地址


	//此时的 * 只是一个标记
	//表示当前是一个指针并记录内存地址

	//2.利用指针去获取变量中的数据
	printf("%d\n",*p1);

	// 打印这一块的星号是解引用运算符表示
	// 通过后面的内存地址去获取对应的数据

	//3.利用指针去存储数据
	*p1 = 200;
	printf("%d\n", *p1);
	printf("%d\n", a);

	//查询数据:  格式: *指针名

	*p1= 20;
	printf("%d\n", *p1);

	//此时为修改数据


	//1.存储数据:  格式: *指针名=数据值;

	//2.指针变量的数据类型要跟指针变量的类型保持一致

	//3.指针变量占用的大小与数据类型无关，跟编译器有关。

	//4.32位:4个字节，64位:8个字节  (有疑问就去看最下面的多行注释)

	//5.给指针变量赋值的时候,不能把一个数值赋给指针变量


	//如:int *p=500;
	//赋值未分配空间的内存地址
	//编译器要先给我们分配才能使用


	//查询数据:*指针名

	//  * :解引用运算符

	char c = 'a';
	char* p2 = &c;

	long long n = 100;
	long long *p3 = &n;

	printf("%zu\n",sizeof(p2));    
	printf("%zu\n", sizeof(p3));   

	//地址变量（指针）的大小，跟它指向什么无关，只跟系统有关。
	//注意：p2 是 char*，但它占的空间不是 1 字节，是 8 字节

	//sizeof(p2)   // 8 —— p2 是地址
	//sizeof(*p2)  // 1 —— *p2 是 c 那一格,char
		//一个是地址，一个是它指的东西。差 8 倍。


	//sizeof(变量) 看什么	变量自己的类型
	//sizeof(指针) 看什么	只看系统位数，跟指向啥无关



	/*
	
	你的理解，逐句确认
		第一句：

		char c → 跟它自己原本的类型有关

		对。​ char 就是 1，写 sizeof(c) 就是 1。不由系统变，只要有 1 字节就够装一个字符。​

		第二句：

		指针的话，不管怎么样都是跟编译器有关，编译器是几位它就是几位

		对。​ 指针 = 地址。地址多宽，取决于地址总线多宽，也就是系统 / 编译器多少位。​

		32 位编译 → 地址 4 字节 → 指针 4
		64 位编译 → 地址 8 字节 → 指针 8
		第三句：

		long long 类型也是同理

		这句要分一半。​

		long long 属于第一类（跟自己的类型有关），不是第二类。

		long long 在任何 64 位平台上都是 8 —— 因为它自己就要求 8
		指针是 8 —— 因为地址是 8
		
		*/










}
