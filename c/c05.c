#include<stdio.h>

int main()
{
	//1.变量只能存在一个值
	// [核心] 变量同一时刻只保存一个值, 新值会覆盖旧值
	int a = 10;
	printf("%d\n",a);

	a = 20;
	printf("%d\n",a);//20

	//2.变量名不可以重复
	//int a = 20;
	//printf("%d\n,a");

	//3,一条语句可以定义多个变量(了解)
	// [注意] 同一作用域内变量名不能重复; 一行定义多个可读性差, 不建议常用
	int b = 10, c = 20, d = 30;
	printf("%d\n", b);
	printf("%d\n", c);
	printf("%d\n", d);
	//4.在使用之前,一定要进行赋值
	//int e;
	//printf("%d\n", e);

	//5.变量的作用范围
	// [补充] 变量的生命周期就是它所在的那对花括号; 出了大括号就失效

	return 0;
}