#define _CRT_SECURE_NO_WARNINGS
#include<stdio.h>
int main()
{
	//1 成立     //0 不成立


	//&& :与,而且  两边都为真,结果才是真.只要有一个不成立,那结果都不成立
	//同时满足
	// [核心] && 全真才真; || 全假才假; ! 取反
	printf("%d\n", 1 && 1); //1
	printf("%d\n", 0 && 0); //0
	printf("%d\n", 1 && 0); //0
	printf("%d\n", 0 && 1); //0
	printf("---------------------\n");



	//|| :或,或者  两边都为假,结果才是假.与&&相反.两边都不成立,才可以
	//二选一
	printf("%d\n", 1 || 1); //1
	printf("%d\n", 0 || 0); //0
	printf("%d\n", 1 || 0); //1
	printf("%d\n", 0 || 1); //1
	printf("---------------------\n");

	//!  :非,取反  取反
	//细节:实际开发当中最多只用一个
	printf("%d\n", !1);  //0
	printf("%d\n", !0);  //1

	int x;
	x <= 0;          // [优化] 废语句: 表达式算完就丢, 没有任何作用, 建议删

	int d;
	d != 3;          // [优化] 同样是废语句, 没有赋值也没有输出
	
	//31~35 为废行



	//需求1.
	//键盘录入两位整数,要求数字中没有7
	//符合,输入1.不符合,输入0
	//88 :1
	//77,17,71:0

	//读题拆解法

	int num1;
	//1,输入
	printf("输入一个两位整数:");
	scanf("%d",&num1);
	printf("\n", num1);
	// [优化] 这行是废代码: 格式串里没有占位符, num1 被白白传进去
	//        想换行直接 printf("\n"); 即可 (建议删掉)

	//2,个位以及十位不能是7
	int ge  = num1 % 10;
	int shi = num1 / 10 % 10;
	
	//3,判断
	//ge != 7, shi != 7;
	printf("%d\n", ge != 7 && shi != 7);



	//需求1.
	//键盘录入两位整数,要求数字中没有7,且这个数不能被7整除
	//符合,输入1.不符合,输入0
	

	int num2;
	//1,输入
	printf("输入一个两位整数:");
	scanf("%d", &num2);
	printf("\n", num2);

	//2,个位以及十位不能是7
	int ge2 = num2 % 10;
	int shi2 = num2 / 10 % 10;

	//3,判断
	//  &&  ||  可以连续写多个
	//  多个&&,表示同时满足多个条件
	//  多个||,表示在多个条件中,进需要满足一个即可
	// 
	// a==1 || a==2|| a==3;
	//满足其中一个即可
	


	//链式&&: 先算(ge2!=7 && shi2!=7)得0/1, 再和(num2%7!=0)算 → 全真才1
	//num2%7!=0 即"余数≠0"=不能被7整除(14%7=0不满足, 88%7=4满足)
	printf("%d\n", ge2 != 7 && shi2 != 7 && num2 % 7 != 0);



	return 0;
}