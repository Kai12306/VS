#include<stdio.h>
int main()
{

	//一.顺序结构
	//1.程序默认执行流程
	//2.从上往下依次进行的


	//二.分支结构
	//1.程序默认执行过程中出现了岔路     (if用于判断,switch用于选择)
	//2.从上往下依次进行的


	// if:满足条件,才可以执行指定的代码
	// 使用场景:某些代码,在满足条件时才执行


	//if的格式:
	//	if (关系表达式)
	//	{
	//
	//		语句体
	//
	//
	//	}

	//需求:判断变量a里面记录的值,是否大于10;若成立,就打印语句:真的大于10
	//定义变量
	/*int a = 22;
	if (a > 10)
	{   
		printf("真的大于10\n");
	}*/

	double tem = 37.8;
	// [补充] 这是"单分支": 条件成立才执行, 不成立啥也不做
	if (tem > 37.5)
	{
		printf("你的体温是:%.3f度\n",tem);
		printf("体温过高,发出警告\n");

	}


	//游戏人物血条
	//需求:初始最大生命是200,受到伤害80,技能回复100
	//问:当前血量是多少?

	//一.定义变量,记录数据
	int blood   = 200;   // 初始最大生命
	int damage  = 200;   // 受到伤害
	int restore = 100;   // 技能回复
	// [易错] damage=200 等于满血, blood 算出是 100; 想演示"血量为负"应让 damage 更大

	//二.游戏的逻辑
	blood = blood - damage + restore;
	printf("blood=%d\n",blood);
	// [核心] 这段在演示"上限制": 超过 200 就硬拉回 200
	// [优化] 更通用的写法是 if (blood > MAX) blood = MAX;, 用常量代替魔法数字 200
	if (blood>200)
	{
		printf("由于血量存在上限\n");
		blood = 200;
		printf("blood=%d\n", blood);
		printf("由于血量上限为200,所以此时血量为200\n");
		printf("血量上限为%d,所以此时血量为%d\n", 200, blood);
		//最后一个为更高级的写法

	}


	//细节1.c语言当中,如果判断结果是一个数字,非零表示条件成立,零则表示条件不成立
	// [重要] C 里"非 0 即真": 5 不是"数字5"而是"真"; 判断为 0 才是假
	// [易错] 别写成 if (a = 5)(赋值), 那也会恒为真, 是经典 bug; 应该写 if (a == 5)
	if (5)
	{
		printf("执行了\n");
	}

	//若大括号里面的语句体只有一行,此时大括号可以不写  (了解即可)

	int a = 22;
	// [补充] 语句体只有一行时可以省大括号, 但省了以后加第二行极易出错
	// [建议] 工程里一律写大括号, 避免"看着在 if 里其实不在"的事故
	if (a > 10)
		printf("真的大于10\n");
	
	//小明正在吃苹果,如果苹果中虫子数量大于等于1,小明就会扔掉苹果
	printf("小明正在吃苹果\n");
	int s = 0;
	printf("小明吃的苹果中虫子的数量:%d\n",s);
	if (s >= 1)
	{
		printf("小明扔掉苹果\n");
	}


	return 0;
}
