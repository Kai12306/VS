#include<stdio.h>
int main()
{

	// [核心] && 和 || 有"短路"效果: 左边能定结果时, 右边根本不执行
	// [重要] 这意味右边如果有 ++/-- 或函数调用, 可能被"跳过"

	/*int a = 0;
	printf("%d\n",a>1 && a<10);


	int b = 10;
	printf("%d\n", b==10 || b==20);*/



	//此时会有短路现象,因为&&是同时满足11才成立
	//而a>1的计算结果是0,就可以直接判断是0
	//即左边表达式可以计算出结果时,右边就可以不用计算了

	int a = 1;
	int b = 5;
	a > 0 && ++b;
	// [推演] a=1 > 0 为真, 所以右边 ++b 被执行, b 变成 6; 但整个表达式的结果没被打印
	printf("a=%d,b=%d\n",a,b);
	a > 10 && ++b;
	// [推演] a=1 > 10 为假, && 左边已为假 -> 短路, 右边 ++b 不执行, b 仍是 6
	printf("x=%d,y=%d\n", a, b);
	// [易错] 格式串写的是 x/y, 实参却是 a/b, 打印出来会误导人; 改成 a=%d,b=%d 更清楚






	return 0;
}