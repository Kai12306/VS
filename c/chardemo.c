#include <stdio.h>

int main()
{
    // 1. 字符用单引号包着，一个字符
    // [核心] char 存的其实是 ASCII 码值; 'A' 存进去的是 65
    char ch = 'A';

    // 2. 看看它到底是什么
    printf("ch 本身 = %c\n", ch);      // %c 按"字符"打印 -> 显示 A
    printf("ch 的数值 = %d\n", ch);    // %d 按"整数"打印 -> 显示 65
    // [核心] 同一个变量, 换个占位符就有两种"看法", 这就是 char 的双重身份

    // 3. 直接拿字符当整数用
    printf("'A' + 1 = %c\n", 'A' + 1);
    // [补充] 65+1=66, 按字符打印就是 'B'; 字符可以直接参与整数运算
    // [易错] 用 %c 打印 66 才出 'B', 用 %d 打印就出 66

    // 4. 几个常用字符的数值
    printf("'A'=%d  'a'=%d  '0'=%d  '1'=%d\n", 'A', 'a', '0', '1');
    // [记忆] 'A'=65 'a'=97 '0'=48 '1'=49
    //        大写和小写相差 32; 数字字符和它代表的数值相差 48

    return 0;
}
